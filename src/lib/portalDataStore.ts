const STORAGE_KEY = "mmes_portal_data_v3";

export function getInitialPortalState(): PortalState {
  const baseState: PortalState = {
    students: initialStudents,
    parentProfile: initialParentProfile,
    teachers: initialTeachers,
    classes: initialClasses,
    timetable: initialTimetable,
    attendanceRecords: initialAttendanceRecords,
    homework: initialHomework,
    homeworkSubmissions: initialHomeworkSubmissions,
    examinations: initialExaminations,
    examSchedules: initialExamSchedules,
    examResults: initialExamResults,
    feeStructures: initialFeeStructures,
    feeInvoices: initialFeeInvoices,
    feePayments: initialFeePayments,
    admissions: initialAdmissions,
    announcements: initialAnnouncements,
    leaveApplications: initialLeaveApplications,
    studyMaterials: initialStudyMaterials,
    notifications: initialNotifications,
    documents: initialSchoolDocuments,
  };

  if (typeof window === "undefined") {
    return baseState;
  }

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(baseState));
      return baseState;
    }
    const parsed = JSON.parse(raw) as Partial<PortalState>;
    return {
      ...baseState,
      ...parsed,
      notifications: parsed.notifications || initialNotifications,
      documents: parsed.documents || initialSchoolDocuments,
    };
  } catch (e) {
    console.error("Failed to load portal state from localStorage:", e);
    return baseState;
  }
}

export function savePortalState(state: PortalState): void {
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
    } catch (e) {
      console.error("Failed to save portal state to localStorage:", e);
    }
  }
}

